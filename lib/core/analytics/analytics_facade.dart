import 'dart:async';

import 'package:asteria_app/core/analytics/analytics_events.dart';
import 'package:asteria_app/core/analytics/apps_flyer_events.dart';
import 'package:asteria_app/core/analytics/durable/analytics_taxonomy.dart';
import 'package:asteria_app/core/analytics/durable/durable_analytics.dart';
import 'package:asteria_app/core/analytics/event_params.dart';
import 'package:asteria_app/core/analytics/feature_names.dart';
import 'package:asteria_app/core/services/apps_flyer_service.dart';

/// Single entry point for product analytics events.
///
/// Product calls are canonicalized here; raw attribution has its own channel.
class AnalyticsFacade {
  AnalyticsFacade({
    required AppsFlyerService appsFlyerService,
    required DurableAnalytics durableAnalytics,
    bool Function(String)? isSourceVisible,
    String? Function()? visibleScreen,
  }) : _appsFlyerService = appsFlyerService,
       _durableAnalytics = durableAnalytics,
       _isSourceVisible = isSourceVisible,
       _visibleScreen = visibleScreen {
    _durableAnalytics.onEventRecorded ??= trackRecordedEvent;
  }

  final AppsFlyerService _appsFlyerService;
  final DurableAnalytics _durableAnalytics;
  final bool Function(String)? _isSourceVisible;
  final String? Function()? _visibleScreen;

  /// Returns after local persistence, independently of either delivery channel.
  Future<void> trackEvent(String name, {Map<String, dynamic>? params}) async {
    if (_isSourceVisible?.call(name) == false) return;
    final event = AnalyticsTaxonomy.map(name, params ?? {});
    // These signals occur only after the backend has accepted the profile.
    // They are server-owned product facts, but must still trigger identify.
    if (name == AnalyticsEvents.signupCompleted ||
        name == 'ast_activation_complete') {
      unawaited(_durableAnalytics.identify());
    }
    final marketing = event == null
        ? AppsFlyerEvents.additional(name, params ?? {})
        : null;
    if (marketing != null &&
        AppsFlyerEvents.isVisible(name, params ?? {}, _visibleScreen?.call())) {
      unawaited(
        _sendMarketing(marketing, AppsFlyerEvents.sanitize(params ?? {})),
      );
    }
    if (event == null) return;
    final marketingParams = AppsFlyerEvents.sanitize(params ?? {});
    var recorded = false;
    try {
      await _durableAnalytics.record(
        event.name,
        event.payload,
        onRecorded: (fact) {
          if (fact['event_name'] == event.name) recorded = true;
          trackRecordedEvent(fact, marketingParams);
        },
      );
      if (event.name == 'feature_result_viewed' &&
          await _durableAnalytics.claimFirstUsefulResult()) {
        unawaited(_sendMarketing('ast_first_useful_result', event.payload));
      }
      unawaited(_durableAnalytics.identify());
    } catch (_) {
      await _durableAnalytics.reportStorageFailure();
    } finally {
      // AF remains independent when collection is disabled or local storage fails.
      if (!recorded) {
        final name = AppsFlyerEvents.fromCanonical(event.name, event.payload);
        if (name != null) {
          unawaited(
            _sendMarketing(name, {...marketingParams, ...event.payload}),
          );
        }
      }
    }
  }

  /// Observes new product facts, never retries or BigQuery acknowledgements.
  void trackRecordedEvent(
    Map<String, Object?> event, [
    Map<String, Object?> extra = const {},
  ]) {
    final payload = Map<String, Object?>.from(event['payload'] as Map);
    final name = AppsFlyerEvents.fromCanonical(
      event['event_name'] as String,
      payload,
    );
    if (name == null) return;
    unawaited(
      _sendMarketing(
        name,
        AppsFlyerEvents.sanitize({
          ...extra,
          ...payload,
          for (final key in [
            'event_id',
            'session_id',
            'app_version',
            'platform',
            'environment',
            'occurred_at',
          ])
            key: event[key],
        }),
      ),
    );
  }

  Future<void> _sendMarketing(String name, Map<String, Object?> params) async {
    try {
      // The warehouse keeps screen; AF reports distinguish screens by name.
      final marketingParams = Map<String, Object?>.of(params);
      if (AppsFlyerEvents.screens.containsValue(name)) {
        marketingParams.remove('screen');
      }
      await _appsFlyerService.logEvent(name, marketingParams);
    } catch (_) {
      // SDK delivery never gates the durable product channel.
    }
  }

  /// Lifecycle events are generated by DurableAnalytics before ATT/SDK startup.
  Future<void> trackAppOpen() async {}

  /// Wrap an actual request, not a screen entry. Success is not a result view.
  Future<T> runFeatureAction<T>(
    String feature,
    Future<T> Function() action,
  ) async {
    final params = {'feature': feature};
    await trackEvent('feature_action_started', params: params);
    try {
      final result = await action();
      if (result == false) {
        await trackEvent('feature_action_failed', params: params);
      }
      return result;
    } catch (_) {
      await trackEvent('feature_action_failed', params: params);
      rethrow;
    }
  }

  // ============================================================
  // Convenience helpers — stable signatures over trackEvent.
  // ============================================================

  Future<void> trackFunnelStep(
    String eventName, {
    required FeatureName feature,
    String? funnelType,
    String? entrySurface,
    String? stepName,
    int? stepIndex,
    Map<String, dynamic>? extra,
  }) {
    return trackEvent(
      eventName,
      params: {
        EventParams.featureName: feature.eventValue,
        if (funnelType != null) EventParams.funnelType: funnelType,
        if (entrySurface != null) EventParams.entrySurface: entrySurface,
        if (stepName != null) EventParams.stepName: stepName,
        if (stepIndex != null) EventParams.stepIndex: stepIndex,
        ...?extra,
      },
    );
  }

  Future<void> trackPaywallView({
    required FeatureName feature,
    String? variant,
    String? offerType,
    String? entrySurface,
  }) {
    return trackEvent(
      AnalyticsEvents.paywallView,
      params: {
        EventParams.featureName: feature.eventValue,
        if (variant != null) EventParams.paywallVariant: variant,
        if (offerType != null) EventParams.offerType: offerType,
        if (entrySurface != null) EventParams.entrySurface: entrySurface,
      },
    );
  }

  Future<void> trackPurchaseSuccess({
    required FeatureName feature,
    String? productId,
    String? packageId,
    num? price,
    String? currency,
    String? purchaseType,
    String? paymentMethod,
  }) {
    return trackEvent(
      AnalyticsEvents.purchaseSuccess,
      params: {
        EventParams.featureName: feature.eventValue,
        if (productId != null) EventParams.productId: productId,
        if (packageId != null) EventParams.packageId: packageId,
        if (price != null) EventParams.price: price,
        if (currency != null) EventParams.currency: currency,
        if (purchaseType != null) EventParams.purchaseType: purchaseType,
        if (paymentMethod != null) EventParams.paymentMethod: paymentMethod,
      },
    );
  }

  Future<void> trackPurchaseFailed({
    required FeatureName feature,
    String? productId,
    String? failureStage,
    String? failureReason,
  }) {
    return trackEvent(
      AnalyticsEvents.purchaseFailed,
      params: {
        EventParams.featureName: feature.eventValue,
        if (productId != null) EventParams.productId: productId,
        if (failureStage != null) EventParams.failureStage: failureStage,
        if (failureReason != null) EventParams.failureReason: failureReason,
      },
    );
  }
}
